# -*- coding: utf-8 -*-
"""§10.2 与 §7.3 补上"站位换组件"这条承重假设。"""
import io, sys
sys.stdout.reconfigure(encoding="utf-8")
p = "../_交付/paper.md"
s = io.open(p, encoding="utf-8").read()

a = "4. **中继站位只取 DEM 格网最高点**。未在连续平面上做位置优化，也未考虑多站间的相互干扰。"
b = ("4. **中继的中途换电假设为「在站位换」**（见 3 节假设 6）。这条假设承重：站 1 需要 2 组能源"
     "组件，而它的缺口段间最长空隙只有 760 s、返场 O01 换一次要 1132 s——**若规定必须返场换电，"
     "站 1 的连续覆盖就断了**，替代方案是中继需求从 3 架升到 4 架。题目只说能源组件「可更换」、"
     "没规定在哪换，本文取了对自己有利的那一种读法，**在这里明确标出**。\n"
     "5. **中继站位只取 DEM 格网最高点**。未在连续平面上做位置优化，也未考虑多站间的相互干扰。")
assert a in s, "MISS 10.2"
s = s.replace(a, b, 1)
s = s.replace("\n5. **组批用子集 DP", "\n6. **组批用子集 DP")
s = s.replace("\n6. **充电周转按", "\n7. **充电周转按")
s = s.replace("\n7. **未考虑风、降水", "\n8. **未考虑风、降水")

# §7.3 补一句指向假设
a2 = "**为什么 3 站以上不再划算。**"
b2 = ("**站 1 需要中途换一次能源组件**（单组可用 2.56 kWh，而它的驻留 7708 s 就吃掉 2.355 kWh，"
      "加往返飞行共 2.728 kWh）。本文按「在站位换组件」处理——这条假设是承重的，"
      "理由与替代方案见 3 节假设 6 与 10.2 节。\n\n"
      "**为什么 3 站以上不再划算。**")
assert a2 in s, "MISS 7.3"
s = s.replace(a2, b2, 1)
io.open(p, "w", encoding="utf-8").write(s)
print("ok")
